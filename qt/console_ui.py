def button(text,handler,symbol=None):
    w=W.QPushButton(text)
    w.setCursor(C.Qt.PointingHandCursor)
    w.clicked.connect(handler)
    if symbol: w.setIcon(icon(symbol))
    return w


def column(widget,margin,spacing):
    box=W.QVBoxLayout(widget)
    box.setContentsMargins(margin,margin,margin,margin)
    box.setSpacing(spacing)
    return box


def group(parent,title):
    frame=W.QFrame()
    frame.setObjectName('panel')
    box=column(frame,16,10)
    heading=label(title,'panelTitle')
    box.addWidget(heading)
    parent.addWidget(frame)
    return frame,box,heading


def chooser(d):
    page=W.QWidget()
    page.setObjectName('chooser')
    outer=column(page,30,0)
    content=W.QWidget()
    content.setMaximumWidth(738)
    content.setSizePolicy(W.QSizePolicy.Expanding,W.QSizePolicy.Preferred)
    box=column(content,0,28)
    box.addWidget(label('选择定位模式','chooserTitle'))
    row=W.QHBoxLayout()
    row.setSpacing(18)
    for mode,title,detail in [('classic','蓝牙模式','连接 iAP2 配件会话或手机 Everywhere App'),
                              ('software','软件模拟模式','自动识别 USB 和 Wi-Fi 设备')]:
        card=ModeCard(title,detail,mode=='classic')
        card.clicked.connect(lambda checked=False,m=mode:d.enter(m))
        row.addWidget(card,1)
    box.addLayout(row)
    d.start_datum=datum_picker('选点底图坐标系')
    d.start_datum.setFixedWidth(200)
    box.addWidget(d.start_datum)
    outer.addStretch()
    center=W.QHBoxLayout()
    center.addStretch(); center.addWidget(content,100); center.addStretch()
    # Keep the selector centered with its Swift maximum width at every window size.
    outer.addLayout(center)
    outer.addStretch()
    return page


def segment(parent,items):
    frame=W.QFrame()
    frame.setObjectName('segments')
    box=column(frame,3,0)
    bar=Segments(items)
    box.addWidget(bar)
    parent.addWidget(frame)
    return bar


def map_area(d):
    d.map=MapView()
    d.map.picked.connect(lambda a,b:d.draft((a,b),False))
    d.map.favorite_picked.connect(lambda name,a,b:d.draft((a,b),name=name))
    # Place controls directly on the map, leaving all other pixels available for picking and panning.
    tools=W.QFrame(d.map)
    tools.setObjectName('mapTools')
    tools.setGeometry(16,16,310,46)
    row=W.QHBoxLayout(tools)
    row.setContentsMargins(9,4,6,4); row.setSpacing(2)
    search=button('搜索地点或地址',lambda:d.places('search'),'search')
    search.setObjectName('searchPill')
    row.addWidget(search,1)
    divider=W.QFrame(); divider.setFixedSize(1,22); divider.setObjectName('separator')
    row.addWidget(divider)
    layers=button('',lambda:d.layers(layers),'layers')
    layers.setObjectName('mapIcon')
    layers.setAccessibleName('地图图层'); layers.setToolTip('地图图层')
    row.addWidget(layers)
    for name,step in [('放大',1),('缩小',-1)]:
        action=d.map.addAction(name)
        action.setShortcut('+' if step>0 else '-')
        action.triggered.connect(lambda checked=False,n=step:d.map.zoom(n))
    refresh=d.map.addAction('刷新当前地图')
    refresh.setShortcuts(G.QKeySequence.StandardKey.Refresh)
    refresh.triggered.connect(d.map.refresh_tiles)
    d.map.setContextMenuPolicy(C.Qt.ActionsContextMenu)
    return d.map


