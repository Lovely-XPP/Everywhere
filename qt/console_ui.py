    panel.setObjectName('inspector')
    panel.setMinimumWidth(350); panel.setMaximumWidth(470)
    side=column(panel,0,0)
    header=W.QWidget()
    header_box=column(header,16,12)
    head=W.QHBoxLayout()
    head.addWidget(Symbol('location',32,'white',True))
    d.title=label('','heading')
    head.addWidget(d.title); head.addStretch()
    d.back=button('切换模式',d.leave); head.addWidget(d.back)
